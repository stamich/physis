plugins {
    id("physis.scala-conventions")
}

description = "Physis simulation core: models, stepping, parameters, runs and manifests."

// physis.core.BuildInfo: framework version and source revision, recorded in run manifests.
val buildInfoDir = layout.buildDirectory.dir("generated/sources/buildinfo/scala/main")
val gitRevision: Provider<String> = providers.exec {
    commandLine("git", "rev-parse", "--short=12", "HEAD")
    isIgnoreExitValue = true
}.standardOutput.asText.map { it.trim() }

val generateBuildInfo by tasks.registering {
    description = "Generates physis.core.BuildInfo."
    val versionText = project.version.toString()
    val revision = gitRevision
    val outputDir = buildInfoDir
    inputs.property("version", versionText)
    inputs.property("git", revision)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().file("physis/core/BuildInfo.scala").asFile
        file.parentFile.mkdirs()
        val git = revision.get()
        val gitLiteral = if (git.isEmpty()) "None" else "Some(\"$git\")"
        file.writeText(
            """
            |package physis.core
            |
            |/** Build metadata, generated by Gradle. */
            |object BuildInfo:
            |  val version: String = "$versionText"
            |  val git: Option[String] = $gitLiteral
            |""".trimMargin()
        )
    }
}

sourceSets {
    main {
        scala.srcDir(generateBuildInfo)
    }
}
